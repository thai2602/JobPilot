-- CV builder schema mapped by CvTemplate, UserCv and the UserCv* child entities.
-- No earlier migration created it: databases initialised before Flyway got these
-- columns and tables from Hibernate ddl-auto=update. Every statement is
-- idempotent so this is a no-op on those databases and completes a fresh one.

ALTER TABLE cv_templates
    ADD COLUMN IF NOT EXISTS description TEXT,
    ADD COLUMN IF NOT EXISTS default_settings JSONB;

ALTER TABLE user_cvs
    ADD COLUMN IF NOT EXISTS template_id BIGINT,
    ADD COLUMN IF NOT EXISTS full_name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS job_title VARCHAR(255),
    ADD COLUMN IF NOT EXISTS email VARCHAR(255),
    ADD COLUMN IF NOT EXISTS phone VARCHAR(20),
    ADD COLUMN IF NOT EXISTS location VARCHAR(255),
    ADD COLUMN IF NOT EXISTS avatar_url TEXT,
    ADD COLUMN IF NOT EXISTS summary TEXT,
    ADD COLUMN IF NOT EXISTS settings JSONB;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint c
        JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
        WHERE c.conrelid = 'user_cvs'::regclass
          AND c.contype = 'f'
          AND a.attname = 'template_id'
    ) THEN
        ALTER TABLE user_cvs
            ADD CONSTRAINT fk_user_cvs_template
            FOREIGN KEY (template_id) REFERENCES cv_templates(id) ON DELETE SET NULL;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS user_cv_experiences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cv_id BIGINT NOT NULL REFERENCES user_cvs(id) ON DELETE CASCADE,
    company VARCHAR(255),
    position VARCHAR(255),
    start_date VARCHAR(20),
    end_date VARCHAR(20),
    description TEXT,
    technologies TEXT[]
);

CREATE TABLE IF NOT EXISTS user_cv_educations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cv_id BIGINT NOT NULL REFERENCES user_cvs(id) ON DELETE CASCADE,
    school VARCHAR(255),
    major VARCHAR(255),
    start_date VARCHAR(20),
    end_date VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS user_cv_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cv_id BIGINT NOT NULL REFERENCES user_cvs(id) ON DELETE CASCADE,
    skill_id BIGINT,
    skill_name VARCHAR(150),
    level VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS user_cv_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cv_id BIGINT NOT NULL REFERENCES user_cvs(id) ON DELETE CASCADE,
    name VARCHAR(255),
    link TEXT,
    description TEXT,
    technologies TEXT[]
);

CREATE TABLE IF NOT EXISTS user_cv_socials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cv_id BIGINT NOT NULL REFERENCES user_cvs(id) ON DELETE CASCADE,
    platform VARCHAR(50),
    url TEXT
);

CREATE TABLE IF NOT EXISTS user_cv_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cv_id BIGINT NOT NULL REFERENCES user_cvs(id) ON DELETE CASCADE,
    name VARCHAR(255),
    organization VARCHAR(255),
    year_or_level VARCHAR(50),
    type VARCHAR(50),
    description TEXT
);

CREATE INDEX IF NOT EXISTS idx_user_cvs_template_id ON user_cvs(template_id);
CREATE INDEX IF NOT EXISTS idx_user_cv_experiences_cv_id ON user_cv_experiences(cv_id);
CREATE INDEX IF NOT EXISTS idx_user_cv_educations_cv_id ON user_cv_educations(cv_id);
CREATE INDEX IF NOT EXISTS idx_user_cv_skills_cv_id ON user_cv_skills(cv_id);
CREATE INDEX IF NOT EXISTS idx_user_cv_projects_cv_id ON user_cv_projects(cv_id);
CREATE INDEX IF NOT EXISTS idx_user_cv_socials_cv_id ON user_cv_socials(cv_id);
CREATE INDEX IF NOT EXISTS idx_user_cv_attachments_cv_id ON user_cv_attachments(cv_id);
